// Regenerates NOTICE.md from the production dependencies. Run: pnpm notice
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';

const listing = JSON.parse(
  execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);

// Packages whose manifest has no licence field but ship a licence file (checked by hand).
const LICENSE_OVERRIDES = { khroma: 'MIT' };

const packages = Object.entries(listing)
  .flatMap(([license, entries]) =>
    entries.map((entry) => ({
      license: license === 'Unknown' ? (LICENSE_OVERRIDES[entry.name] ?? license) : license,
      name: entry.name,
      homepage: entry.homepage,
    })),
  )
  .sort((a, b) => a.license.localeCompare(b.license) || a.name.localeCompare(b.name));

const rows = packages.map(
  (p) => `| ${p.name} | ${p.license} | ${p.homepage ? `<${p.homepage}>` : ''} |`,
);

const out = `# Third-party notices

OpenMinutes is licensed under AGPL-3.0-only, see [LICENSE](LICENSE). It includes and downloads the third-party software and models below, each under its own licence. This file is generated by \`pnpm notice\`; do not edit it by hand.

## JavaScript dependencies

Production dependencies of all workspace packages, including transitive ones.

| Package | Licence | Homepage |
| ------- | ------- | -------- |
${rows.join('\n')}

## Whisper service (Python)

| Package | Licence |
| ------- | ------- |
| fastapi | MIT |
| uvicorn | BSD-3-Clause |
| python-multipart | Apache-2.0 |
| faster-whisper | MIT |
| av (PyAV) | BSD-3-Clause |
| requests | Apache-2.0 |
| sherpa-onnx | Apache-2.0 |

## Models

Downloaded on first use, not shipped in this repository.

| Model | Licence | Source |
| ----- | ------- | ------ |
| Whisper (CTranslate2 conversions used by faster-whisper) | MIT | <https://github.com/openai/whisper> |
| pyannote segmentation 3.0 (ONNX export for sherpa-onnx) | MIT | <https://huggingface.co/pyannote/segmentation-3.0> |
| 3D-Speaker ERes2Net speaker embedding (VoxCeleb, English) | Apache-2.0 | <https://github.com/modelscope/3D-Speaker> |

## Container images

The images are built on Debian and the official Node.js image and include ffmpeg (LGPL/GPL) and Chromium (BSD-3-Clause and others) from the Debian archive. Their licence texts are in \`/usr/share/doc\` inside the images.
`;

writeFileSync(new URL('../NOTICE.md', import.meta.url), out);
process.stdout.write(`NOTICE.md written with ${packages.length} packages\n`);
