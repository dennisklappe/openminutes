// Copies the rules of the real web app stylesheets that the demo uses into src/demo/app.css,
// scoped under .omd, so the demo looks like the app without a second copy to keep in step.
// A rule is kept when every class in one of its selectors is mentioned in src/demo/*.ts.
// Usage: node scripts/demo/app-css.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { URL, fileURLToPath } from 'node:url';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const sheets = [
  'styles.css',
  'voices.css',
  'speakerReview.css',
  'participants/participants.css',
  'recorder/recorder.css',
];
const source = sheets
  .map((name) => readFileSync(here(`../../../apps/web/ui/${name}`), 'utf8'))
  .join('\n')
  .replace(/\/\*[\s\S]*?\*\//g, '');
const demoDir = here('../../src/demo/');
const words = new Set(
  readdirSync(demoDir)
    .filter((name) => name.endsWith('.ts'))
    .flatMap((name) => readFileSync(demoDir + name, 'utf8').match(/[A-Za-z][\w-]*/g) ?? []),
);

const SKIPPED_ROOTS = /^(html|body|:root|\*|::selection)\b/;

function blocks(css) {
  const found = [];
  let depth = 0;
  let start = 0;
  let open = -1;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') {
      if (depth++ === 0) open = i;
    } else if (css[i] === '}' && --depth === 0) {
      found.push({ head: css.slice(start, open).trim(), body: css.slice(open + 1, i) });
      start = i + 1;
    } else if (css[i] === ';' && depth === 0) {
      start = i + 1;
    }
  }
  return found;
}

const splitSelectors = (head) => head.split(/,(?![^(]*\))/).map((part) => part.trim());
const usable = (selector) =>
  !SKIPPED_ROOTS.test(selector) &&
  !selector.includes('[data-theme') &&
  (selector.match(/\.[A-Za-z][\w-]*/g) ?? []).every((name) => words.has(name.slice(1)));

function scoped(css) {
  return blocks(css)
    .map(({ head, body }) => {
      if (head.startsWith('@keyframes'))
        return words.has(head.split(/\s+/)[1] ?? '') ? `${head}{${body}}` : '';
      if (head.startsWith('@')) {
        const inner = scoped(body);
        return inner ? `${head}{\n${inner}}\n` : '';
      }
      const kept = splitSelectors(head).filter(usable);
      return kept.length
        ? `${kept.map((selector) => `.omd ${selector}`).join(',\n')} {${body}}\n`
        : '';
    })
    .join('');
}

writeFileSync(
  here('../../src/demo/app.css'),
  `/* Generated by scripts/demo/app-css.mjs from the apps/web/ui stylesheets. Do not edit. */\n${scoped(source)}`,
);
